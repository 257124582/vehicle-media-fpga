def fn(name,strings):
    lines=[f'function [7:0] {name};input [4:0] row;input [5:0] col;begin',f"{name}=8'd32;case(row)"]
    for row,string in enumerate(strings):
        lines.append(f'{row}:case(col)')
        for col,c in enumerate(string):lines.append(f"{col}:{name}=8'd{code[c]};")
        lines.append('endcase')
    return '\n'.join(lines+['endcase end endfunction'])
